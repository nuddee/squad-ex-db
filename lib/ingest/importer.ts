import { readFileSync, readdirSync, statSync } from "node:fs";
import path from "node:path";
import { parseCsv } from "@/lib/qc/parse";
import { isImageFilename } from "@/lib/qc/snapshot-meta";
import { attachWeight, formatReport, ingestRows, mergeReports, MAX_ROWS_PER_REQUEST, type IngestReport } from "./core";
import { snapshotPaths, validateSnapshotFilename, type RejectReason } from "./snapshots";
import type { IngestStore } from "./store";
import { parseSnapshotMeta } from "@/lib/qc/snapshot-meta";

export interface SnapshotImportReport {
  found: number;
  stored: number;
  rejected: number;
  reject_reasons: Partial<Record<RejectReason | "upload_failed", number>>;
}

export interface ImportReport {
  file: string;
  ingest: IngestReport;
  snapshots: SnapshotImportReport | null;
  dry_run: boolean;
}

/** Uploads one image to storage. Injected so dry-run and tests need no network. */
export type SnapshotUploader = (storagePath: string, bytes: Buffer, filename: string) => Promise<void>;

export interface ImportOptions {
  store: IngestStore;
  csvPath: string;
  deviceId: string | null;
  snapshotsDir?: string;
  uploader?: SnapshotUploader;
  dryRun?: boolean;
}

/** Backfill one legacy CSV (and optionally its snapshots folder). Idempotent: re-running updates in place. */
export async function importCsv(o: ImportOptions): Promise<ImportReport> {
  const sourceName = path.basename(o.csvPath);
  const table = parseCsv(readFileSync(o.csvPath, "utf8"));
  const header = table[0] ?? [];
  const records = table.slice(1);

  const chunks: IngestReport[] = [];
  for (let i = 0; i < records.length; i += MAX_ROWS_PER_REQUEST) {
    chunks.push(
      await ingestRows(
        o.store,
        { deviceId: o.deviceId, sourceName, columns: header, rows: records.slice(i, i + MAX_ROWS_PER_REQUEST), firstRecord: i + 1 },
        { computeWeight: false },
      ),
    );
  }
  if (chunks.length === 0) {
    chunks.push(await ingestRows(o.store, { deviceId: o.deviceId, sourceName, columns: header, rows: [] }, { computeWeight: false }));
  }
  const ingest = mergeReports(chunks, sourceName);
  await attachWeight(o.store, ingest); // once, over the whole batch

  let snapshots: SnapshotImportReport | null = null;
  if (o.snapshotsDir && ingest.batch_id) {
    snapshots = await importSnapshotsDir(o, ingest.batch_id);
  } else if (o.snapshotsDir && !ingest.batch_id) {
    ingest.warnings.push(
      `SNAPSHOTS NOT IMPORTED: snapshots directory "${o.snapshotsDir}" was provided, but the CSV yielded no valid inspection rows (no batch was created).`,
    );
  }
  return { file: o.csvPath, ingest, snapshots, dry_run: !!o.dryRun };
}

async function importSnapshotsDir(o: ImportOptions, batchId: string): Promise<SnapshotImportReport> {
  const settings = await o.store.getSettings();
  const names = readdirSync(o.snapshotsDir!).filter((n) => statSync(path.join(o.snapshotsDir!, n)).isFile());
  const rep: SnapshotImportReport = { found: 0, stored: 0, rejected: 0, reject_reasons: {} };
  const bump = (r: RejectReason | "upload_failed") => {
    rep.rejected++;
    rep.reject_reasons[r] = (rep.reject_reasons[r] ?? 0) + 1;
  };
  const records = [];
  for (const filename of names) {
    if (!isImageFilename(filename)) continue; // not an image (e.g. Thumbs.db): ignore silently
    rep.found++;
    const why = validateSnapshotFilename(filename);
    if (why) { bump(why); continue; }
    const paths = snapshotPaths(batchId, filename);
    try {
      if (o.uploader && !o.dryRun) await o.uploader(paths.image, readFileSync(path.join(o.snapshotsDir!, filename)), filename);
    } catch {
      bump("upload_failed");
      continue;
    }
    const meta = parseSnapshotMeta(filename, settings.snapshot_filename_tz);
    // No thumbnail is generated by the importer; thumb_path stays null and the UI falls back to the full image.
    records.push({ filename, storage_path: paths.image, thumb_path: null, plate_number: meta.plate, captured_at: meta.ts });
    rep.stored++;
  }
  if (records.length) await o.store.upsertSnapshots(batchId, records);
  return rep;
}

export function formatImportReport(r: ImportReport): string {
  const lines = [formatReport(r.ingest)];
  if (r.snapshots) {
    const s = r.snapshots;
    lines.push(
      `  snapshots: found ${s.found}, stored ${s.stored}, rejected ${s.rejected}` +
        (s.rejected ? ` (${Object.entries(s.reject_reasons).map(([k, v]) => `${k}=${v}`).join(", ")})` : ""),
    );
  }
  if (r.dry_run) lines.push("  (dry run: nothing was written)");
  return lines.join("\n");
}
